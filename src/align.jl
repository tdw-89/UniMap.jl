"""
    maxins_from_args(args) -> Union{Int,Nothing}

Value of bowtie2 `-X`/`--maxins` in an argument vector, if given.
"""
function maxins_from_args(args::AbstractVector{<:AbstractString})
    for (i, a) in enumerate(args)
        (a == "-X" || a == "--maxins") && i < length(args) && return parse(Int, args[i+1])
        startswith(a, "--maxins=") && return parse(Int, a[10:end])
    end
    return nothing
end

function read_simulate_toml(simdir::AbstractString)
    path = joinpath(simdir, "simulate.toml")
    isfile(path) || error("$path not found; is '$simdir' a `unimap simulate` output directory?")
    return TOML.parsefile(path)
end

"""
    write_align_script(simdir; index, threads=4, aligner_args="", bowtie2="bowtie2", samtools="samtools")

Write `simdir/align.sh`, a bash script that aligns the simulated pairs for
each read length with one bowtie2 run per L, producing unsorted, unfiltered
`aln/sim_L{L}.bam`. `aligner_args` should be the production arguments; `-X` is set to
the largest simulated fragment length if absent. Also writes `align.toml` recording the settings.
"""
function write_align_script(simdir::AbstractString; index::AbstractString, threads::Integer=4,
                            aligner_args::AbstractString="", bowtie2::AbstractString="bowtie2",
                            samtools::AbstractString="samtools")
    out = joinpath(simdir, "align.sh")
    meta = read_simulate_toml(simdir)
    fmax = maximum(meta["grid"]["fragment_lengths"])
    Ls = meta["grid"]["read_lengths"]
    args = Base.shell_split(aligner_args)
    any(a -> a in ("--no-unal", "-p", "--threads", "-x", "-1", "-2", "-U", "-S"), args) &&
        error("aligner args must not set --no-unal, threads, index, inputs or output (they are handled by the script)")
    X = maxins_from_args(args)
    if X === nothing
        append!(args, ["-X", string(fmax)])
    elseif X != fmax
        @warn "aligner -X $X differs from the largest simulated fragment length $fmax; fragments longer than $X cannot align as proper pairs"
    end
    isfile(index * ".1.bt2") || isfile(index * ".1.bt2l") ||
        @warn "no bowtie2 index found at prefix $index (fine if the script will run elsewhere)"

    q(s) = Base.shell_escape(s)
    script = """
    #!/usr/bin/env bash
    # Generated by `unimap align-script` (UniMap $(pkgversion(@__MODULE__))) on $(now()).
    # One bowtie2 run per read length over all loci; BAMs are left unsorted and unfiltered.
    set -euo pipefail

    INDEX=$(q(abspath(index)))
    THREADS=$(threads)
    BOWTIE2=$(q(bowtie2))
    SAMTOOLS=$(q(samtools))
    ALIGNER_ARGS=($(join(q.(args), ' ')))
    READ_LENGTHS=($(join(Ls, ' ')))

    cd "\$(dirname "\${BASH_SOURCE[0]}")"
    mkdir -p aln
    "\$BOWTIE2" --version > aln/bowtie2_version.txt

    locus_ids() { tail -n +2 loci.tsv | cut -f1; }
    # Concatenate one mate's FASTQ across loci in loci.tsv order, so R1/R2 stay in step.
    mates() { locus_ids | while read -r id; do gzip -dc "fastq/L\$1/\${id}_\$2.fq.gz"; done; }

    for L in "\${READ_LENGTHS[@]}"; do
        bam="aln/sim_L\${L}.bam"
        if [[ -e "\$bam.done" ]]; then
            echo "L=\$L already aligned; skipping"
            continue
        fi
        while read -r id; do
            for r in R1 R2; do
                [[ -s "fastq/L\$L/\${id}_\$r.fq.gz" ]] || { echo "missing fastq/L\$L/\${id}_\$r.fq.gz" >&2; exit 1; }
            done
        done < <(locus_ids)
        echo "[\$(date)] aligning L=\$L"
        "\$BOWTIE2" -x "\$INDEX" --threads "\$THREADS" "\${ALIGNER_ARGS[@]}" \\
            -1 <(mates "\$L" R1) -2 <(mates "\$L" R2) 2> "aln/sim_L\${L}.bowtie2.log" \\
            | "\$SAMTOOLS" view -b -o "\$bam" -
        touch "\$bam.done"
    done
    echo "[\$(date)] done"
    """
    write(out, script)
    chmod(out, 0o755)
    open(joinpath(simdir, "align.toml"), "w") do io
        TOML.print(io, Dict("aligner" => "bowtie2", "index" => abspath(index), "threads" => threads,
                            "aligner_args" => args, "bowtie2" => bowtie2, "samtools" => samtools,
                            "script" => abspath(out), "created" => string(now())))
    end
    return out
end
